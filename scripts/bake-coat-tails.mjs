import {collectBakeProvenance} from './lib/bake-provenance.mjs';
import * as THREE from 'three';
import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {loadCharacterRig} from '../preview/tests/helpers/character-rig.js';
import {loadResidentAvatar} from '../preview/src/avatars.js';
import {createCoatTailGeometry,COAT_WAIST} from '../preview/src/coat-tail-geometry.js';
import {skinCoatTails} from '../preview/src/coat-tail-skinning.js';
import {prepareDrapeSeatFit} from './lib/drape-seat-fit.mjs';
import {coatTailSeatPoint} from './lib/coat-tail-fit.mjs';
import {skirtContactFixture} from '../preview/tests/helpers/skirt-contact.js';
import {garmentEdgeFixture} from '../preview/tests/helpers/garment-edges.js';

const write=process.argv.includes('--write');
if(process.argv.slice(2).some(arg=>!['--write','--check'].includes(arg)))throw new Error('Use --check or --write');
const root=new URL('../',import.meta.url),source=await loadCharacterRig('man-casual');
const previousLoad=GLTFLoader.prototype.loadAsync,previousWindow=globalThis.window,previousDocument=globalThis.document;
GLTFLoader.prototype.loadAsync=async()=>({scene:source.scene});
globalThis.window={matchMedia:()=>({matches:false})};globalThis.document={createElement:()=>({getContext:()=>new Proxy({},{get:()=>()=>{}})})};
const data={},diagnostics={};
const pack=values=>{const bytes=Buffer.alloc(values.length*4);values.forEach((value,i)=>bytes.writeFloatLE(value,i*4));return bytes.toString('base64');};
try{
  for(const character of ['kai','aurel']){
    const avatar=await loadResidentAvatar(4,'remote-coat-bake','man-casual',{folk:false,appearanceId:'man-casual',faceRecipe:{}});
    const model=avatar.rig.model,pelvis=model.getObjectByName('pelvis'),body=model.getObjectByName('man-casualmale_casualsuit02');model.updateWorldMatrix(true,true);
    const attachment=new THREE.Group();attachment.quaternion.copy(pelvis.getWorldQuaternion(new THREE.Quaternion()).invert().multiply(model.getWorldQuaternion(new THREE.Quaternion())));pelvis.add(attachment);
    const geometry=createCoatTailGeometry(character),material=new THREE.MeshBasicMaterial({side:THREE.DoubleSide}),raw=new THREE.Mesh(geometry,material);attachment.add(raw);
    const {mesh,group}=skinCoatTails(raw,body);
    const contact=skirtContactFixture(model,body,mesh),edges=garmentEdgeFixture(model,body,[mesh]),fit=prepareDrapeSeatFit(mesh,model,{waist:COAT_WAIST,body,shape:coatTailSeatPoint,lapClearance:.035});
    const positions=geometry.attributes.position.array.slice(),weights=geometry.attributes.skinWeight.array.slice(),normals=geometry.attributes.normal.array.slice();
    try{
      avatar.object.position.y=.55-avatar.rig.hipHeight+.025;
      for(let frame=0;frame<=144;frame++)avatar.update(frame*1000/60,'continue',false,{speed:0,distance:0,riding:true,ridingKind:'seat',seatToFloor:.55},()=>0);
      const fitting=fit(),lap=contact.sample(),edge=edges.sample();diagnostics[character]={...fitting,...lap,edges:edge};
      if(lap.tested<100||lap.penetrating||edge.some(r=>r.crossings))throw new Error(`Coat fit failed: ${JSON.stringify(diagnostics[character])}`);
      data[character]={version:1,subdivide:false,sourcePositions:pack(positions),sourceWeights:pack(weights),
        positionDelta:pack(Array.from(geometry.attributes.position.array,(value,i)=>Math.fround(value-positions[i]))),
        normalDelta:pack(Array.from(geometry.attributes.normal.array,(value,i)=>Math.fround(value-normals[i])))};
    }finally{edges.dispose();contact.dispose();group.removeFromParent();attachment.removeFromParent();geometry.dispose();material.dispose();avatar.dispose();}
  }
  const output="// Generated by node scripts/bake-coat-tails.mjs --write. See adjacent receipt.\nimport {unpackMorphData} from './packed-morph-data.js';\nexport const COAT_TAIL_MORPHS = Object.fromEntries(Object.entries("+JSON.stringify(data)+").map(([key,value])=>[key,unpackMorphData(value)]));\n";
  const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
  const {inputs, toolchain} = await collectBakeProvenance({root, bake: 'coat-tail'});
  const receipt=JSON.stringify({version:2,provenance:'Repository-authored split coat surfaces; shipped rig source/license in sources.json.',command:'node scripts/bake-coat-tails.mjs --check',inputs,toolchain,outputSha256:hash(output),diagnostics},null,2)+'\n';
  for(const [path,expected]of [['preview/src/coat-tail-morph-data.js',output],['preview/src/coat-tail-morph-receipt.json',receipt]]){
    if(write)await writeFile(new URL(path,root),expected);else if(await readFile(new URL(path,root),'utf8')!==expected)throw new Error(`Bake differs: ${path}`);
  }
  console.log(JSON.stringify({status:write?'written':'verified',diagnostics}));
}finally{GLTFLoader.prototype.loadAsync=previousLoad;globalThis.window=previousWindow;globalThis.document=previousDocument;}
