#!/usr/bin/env node
// Writes docs/superpowers/plans/README.md: every plan ledger with its status
// from the task register, so a reader can see which plans are live, delivered
// or historical without opening each one. Run `pnpm run plans:index` after the
// register changes; `--check` exits 1 when the index is out of date.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const GROUPS = [
  ['Active and blocked', task => ['active', 'blocked', 'queued'].includes(task.status)],
  ['Delivered, awaiting local retirement', task => task.status === 'delivered'],
  ['Retired', task => task.status === 'retired'],
];
const cell = text => String(text ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const titleOf = text => text.match(/^#\s+(.+)$/m)?.[1]?.trim() ?? null;
const prsIn = text => [...new Set([...text.matchAll(/(?<![\w/])#(\d{2,4})\b/g)].map(match => Number(match[1])))].slice(0, 3);

export function renderPlansIndex({ tasks, plans }) {
  const byLedger = new Map();
  for (const task of tasks) if (task.ledger) byLedger.set(basename(task.ledger), [...(byLedger.get(basename(task.ledger)) ?? []), task]);
  const rows = { linked: [], historical: [] };
  for (const plan of [...plans].sort((a, b) => b.file.localeCompare(a.file))) {
    const title = cell(titleOf(plan.text) ?? plan.file.replace(/\.md$/, ''));
    const linked = byLedger.get(plan.file);
    if (linked) for (const task of linked) rows.linked.push({ plan, title, task });
    else rows.historical.push({ plan, title });
  }
  const link = plan => `[${plan.file.replace(/\.md$/, '')}](${plan.file})`;
  const out = ['# Plans index', '',
    '<!-- Generated by `pnpm run plans:index` from docs/project-management/tasks.json. Do not edit by hand. -->', '',
    'Each plan is a task ledger. Status comes from the task register, where the primary checkout\'s live copy can be newer than the committed one. Plans from before the register are listed as historical: their own text is the record of what was delivered.', ''];
  for (const [heading, match] of GROUPS) {
    const group = rows.linked.filter(row => match(row.task));
    out.push(`## ${heading} (${group.length})`, '');
    if (!group.length) { out.push('None.', ''); continue; }
    out.push('| Plan | Task | Status | PR | Updated |', '| --- | --- | --- | --- | --- |');
    for (const { plan, title, task } of group) {
      const pr = task.deliveryPr ?? task.pr;
      out.push(`| ${link(plan)}<br>${title} | \`${cell(task.id)}\` | ${cell(task.status)} | ${pr ? `#${pr}` : '—'} | ${cell(String(task.updatedAt ?? '').slice(0, 10)) || '—'} |`);
    }
    out.push('');
  }
  out.push(`## Historical, not in the register (${rows.historical.length})`, '', '| Plan | PRs mentioned |', '| --- | --- |');
  for (const { plan, title } of rows.historical) {
    const prs = prsIn(plan.text);
    out.push(`| ${link(plan)}<br>${title} | ${prs.length ? prs.map(n => `#${n}`).join(', ') : '—'} |`);
  }
  return out.join('\n') + '\n';
}

export function plansIndexFor(root) {
  const directory = join(root, 'docs/superpowers/plans');
  const plans = readdirSync(directory).filter(file => file.endsWith('.md') && file !== 'README.md')
    .map(file => ({ file, text: readFileSync(join(directory, file), 'utf8') }));
  const { tasks } = JSON.parse(readFileSync(join(root, 'docs/project-management/tasks.json'), 'utf8'));
  return { path: join(directory, 'README.md'), text: renderPlansIndex({ tasks, plans }) };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = fileURLToPath(new URL('..', import.meta.url));
  const { path, text } = plansIndexFor(root);
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(path, 'utf8'); } catch { /* Missing counts as stale. */ }
    if (current !== text) { process.stderr.write('plans-index: docs/superpowers/plans/README.md is out of date; run pnpm run plans:index\n'); process.exitCode = 1; }
  } else writeFileSync(path, text);
}
