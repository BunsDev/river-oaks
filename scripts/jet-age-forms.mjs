#!/usr/bin/env node
// Reproducible Jet-Age form assets (#738, #741): writes the vocabulary's manifest (version,
// per-form point counts and digests) and a contact sheet SVG drawn from the same pure profiles
// the renderer uses (shared/city-kit/jet-age-forms.js). Output is byte-stable for a given
// JET_AGE_FORMS_VERSION, so a diff in either file means a profile changed.
//
//   node scripts/jet-age-forms.mjs [--out=docs/design/pink-jet-age] [--check]
//
// --check writes nothing and exits 1 when the committed files differ from a fresh render.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { JET_AGE_FORMS, jetAgeFormsManifest } from '../shared/city-kit/jet-age-forms.js';
import { PINK_JET_AGE as P } from '../shared/city-kit/pink-jet-age.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = Object.fromEntries(process.argv.slice(2).map(arg => arg.replace(/^--/, '').split('=')).map(([key, value]) => [key, value ?? true]));
const out = resolve(root, typeof args.out === 'string' ? args.out : 'docs/design/pink-jet-age');

const CELL = 240, PAD = 28, COLUMNS = 4;
const fmt = n => (Math.round(n * 100) / 100).toString();

// One cell per form: its points fitted into the cell, y up. Closed outlines are filled.
function cell(name, index) {
  const data = JET_AGE_FORMS[name].make(), x0 = (index % COLUMNS) * CELL, y0 = Math.floor(index / COLUMNS) * CELL;
  let points, closed = true, extra = '';
  if (name === 'starburst') {
    // Rays projected onto the x/y plane from the hub.
    points = null;
    const s = (CELL / 2 - PAD) / 1.05, cx = x0 + CELL / 2, cy = y0 + CELL / 2 + 6;
    extra = data.map(ray => `<line x1="${fmt(cx)}" y1="${fmt(cy)}" x2="${fmt(cx + ray.direction[0] * ray.length * s)}" y2="${fmt(cy - ray.direction[1] * ray.length * s)}" stroke="${P.chrome}" stroke-width="3" stroke-linecap="round"/><circle cx="${fmt(cx + ray.direction[0] * ray.length * s)}" cy="${fmt(cy - ray.direction[1] * ray.length * s)}" r="4" fill="${P.pink}"/>`).join('') + `<circle cx="${fmt(cx)}" cy="${fmt(cy)}" r="7" fill="${P.ink}"/>`;
  } else {
    // Lathe profiles are mirrored so the solid reads whole; centrelines are open strokes.
    const mirrored = name === 'saucer' || name === 'tapered-column';
    points = mirrored ? [...data, ...data.slice().reverse().map(([x, y]) => [-x, y])] : data;
    closed = !['parabolic-arch', 'hoop'].includes(name);
  }
  let shape = extra;
  if (points) {
    const xs = points.map(p => p[0]), ys = points.map(p => p[1]);
    const [minX, maxX, minY, maxY] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
    // Thin profiles (saucer, canopy) keep true proportions but get a readable minimum height.
    const sx = (CELL - 2 * PAD) / Math.max(maxX - minX, 1e-6), sy = (CELL - 2 * PAD - 26) / Math.max(maxY - minY, 1e-6), s = Math.min(sx, sy);
    const ox = x0 + CELL / 2 - ((minX + maxX) / 2) * s, oy = y0 + CELL / 2 + 6 + ((minY + maxY) / 2) * s;
    const d = points.map(([x, y], i) => `${i ? 'L' : 'M'}${fmt(ox + x * s)} ${fmt(oy - y * s)}`).join(' ') + (closed ? ' Z' : '');
    shape = closed ? `<path d="${d}" fill="${P.ivory}" stroke="${P.pink}" stroke-width="2.5" stroke-linejoin="round"/>` : `<path d="${d}" fill="none" stroke="${P.chrome}" stroke-width="6" stroke-linecap="round" stroke-linejoin="round"/>`;
  }
  return `<g><rect x="${x0 + 6}" y="${y0 + 6}" width="${CELL - 12}" height="${CELL - 12}" rx="22" fill="#ffffff" stroke="${P.mintGlass}"/>${shape}<text x="${x0 + CELL / 2}" y="${y0 + CELL - 18}" text-anchor="middle" font-family="Helvetica, Arial, sans-serif" font-size="15" fill="${P.ink}">${name}</text></g>`;
}

const names = Object.keys(JET_AGE_FORMS), manifest = jetAgeFormsManifest(), rows = Math.ceil(names.length / COLUMNS);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${COLUMNS * CELL}" height="${rows * CELL + 44}" viewBox="0 0 ${COLUMNS * CELL} ${rows * CELL + 44}">
<rect width="100%" height="100%" fill="${P.ivory}"/>
<text x="16" y="28" font-family="Helvetica, Arial, sans-serif" font-size="18" font-weight="bold" fill="${P.ink}">Pink Jet-Age form vocabulary · ${manifest.version} · generated by scripts/jet-age-forms.mjs</text>
<g transform="translate(0 44)">${names.map(cell).join('\n')}</g>
</svg>
`;
const json = `${JSON.stringify({ ...manifest, generator: 'scripts/jet-age-forms.mjs', source: 'shared/city-kit/jet-age-forms.js', license: 'Project-original, generated from source; no third-party assets.' }, null, 2)}\n`;

const files = [[join(out, 'jet-age-forms.svg'), svg], [join(out, 'jet-age-forms.json'), json]];
if (args.check) {
  const stale = files.filter(([path, text]) => { try { return readFileSync(path, 'utf8') !== text; } catch { return true; } });
  for (const [path] of stale) console.error(`stale: ${path}`);
  process.exit(stale.length ? 1 : 0);
}
mkdirSync(out, { recursive: true });
for (const [path, text] of files) { writeFileSync(path, text);console.log(`wrote ${path}`); }
