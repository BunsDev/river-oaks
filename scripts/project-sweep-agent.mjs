#!/usr/bin/env node
// Install, inspect or remove the macOS launch agent that runs project:sweep on a
// schedule. Worktrees are local to this machine, so the schedule is local too.
//
// Each run fetches origin, stages origin/main's scripts/ outside every worktree and
// runs the sweep from there against the primary checkout, so the schedule always
// uses current main tooling even when the primary checkout sits on an older branch.
// It is report-only unless installed with --apply; --apply retires only what
// project:prune would accept (an owner's fresh exact-head release included).
import { execFileSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export const LABEL = 'dev.bunsdev.river-oaks.project-sweep';
const sh = value => "'" + String(value).replaceAll("'", "'\\''") + "'";
const xml = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&apos;');

export function renderRunner({ root, stateDir, node, path, apply, staleLeaseHours = 24, fallbackRef = null }) {
  const stage = join(stateDir, 'stage');
  // Until the sweep reaches main, an install can name the branch that carries it.
  // main always wins once it has the script; a vanished fallback is a run error.
  const pick = fallbackRef
    ? `REF=refs/remotes/origin/main
if ! git -C "$ROOT" cat-file -e "$REF:scripts/project-sweep.mjs" 2>/dev/null; then
  REF=${sh(fallbackRef)}
  echo "origin/main has no project-sweep.mjs yet; staging $REF"
fi`
    : 'REF=refs/remotes/origin/main';
  return `#!/bin/sh
# Generated by scripts/project-sweep-agent.mjs; reinstall rather than edit.
set -eu
export PATH=${sh(path)}
ROOT=${sh(root)}
STAGE=${sh(stage)}
echo "== project-sweep $(date -u +%Y-%m-%dT%H:%M:%SZ)"
git -C "$ROOT" fetch --quiet --no-prune origin
${pick}
rm -rf "$STAGE.next"
mkdir -p "$STAGE.next"
git -C "$ROOT" archive "$REF" scripts | tar -x -C "$STAGE.next"
rm -rf "$STAGE"
mv "$STAGE.next" "$STAGE"
cd "$STAGE"
set +e
${sh(node)} "$STAGE/scripts/project-sweep.mjs" --repo "$ROOT" --no-fetch --notify --stale-lease-hours ${Number(staleLeaseHours)}${apply ? ' --apply' : ''} > /dev/null
status=$?
echo "exit $status (0 clear, 1 action queue, 2 error); receipt: $ROOT/.runtime/project-sweep/latest.md"
exit $status
`;
}

export function renderPlist({ label = LABEL, runner, stateDir, intervalMinutes }) {
  const log = join(stateDir, 'sweep.log');
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${xml(label)}</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/sh</string>
    <string>${xml(runner)}</string>
  </array>
  <key>StartInterval</key>
  <integer>${intervalMinutes * 60}</integer>
  <key>RunAtLoad</key>
  <false/>
  <key>ProcessType</key>
  <string>Background</string>
  <key>LowPriorityIO</key>
  <true/>
  <key>Nice</key>
  <integer>10</integer>
  <key>StandardOutPath</key>
  <string>${xml(log)}</string>
  <key>StandardErrorPath</key>
  <string>${xml(log)}</string>
</dict>
</plist>
`;
}

const USAGE = 'Usage: project:sweep-agent <print|install|uninstall|status> [--repo <primary checkout>] [--interval-minutes <n>=60] [--stale-lease-hours <h>=24] [--node <path>] [--fallback-ref refs/remotes/origin/<branch>] [--apply]';

export function parseAgentArgs(args) {
  const [command = 'print', ...rest] = args;
  if (!['print', 'install', 'uninstall', 'status'].includes(command)) throw new Error(USAGE);
  const values = {}; let apply = false;
  for (let i = 0; i < rest.length; i++) {
    if (rest[i] === '--apply') { apply = true; continue; }
    if (!['--repo', '--interval-minutes', '--stale-lease-hours', '--node', '--fallback-ref'].includes(rest[i]) || !rest[i + 1] || rest[i + 1].startsWith('--')) throw new Error(USAGE);
    values[rest[i]] = rest[++i];
  }
  const intervalMinutes = Number(values['--interval-minutes'] ?? 60), staleLeaseHours = Number(values['--stale-lease-hours'] ?? 24);
  // The owner release is only fresh for two hours, so the interval must leave room for it.
  if (!Number.isInteger(intervalMinutes) || intervalMinutes < 15 || intervalMinutes > 110) throw new Error('--interval-minutes must be an integer from at least 15 to 110 (a release stays fresh for two hours)');
  if (!(staleLeaseHours > 0)) throw new Error('--stale-lease-hours must be positive');
  const fallbackRef = values['--fallback-ref'] ?? null;
  if (fallbackRef && !/^refs\/remotes\/origin\/[\w./-]+$/.test(fallbackRef)) throw new Error('--fallback-ref must be a refs/remotes/origin/<branch> ref');
  return { command, repo: values['--repo'], node: values['--node'], fallbackRef, intervalMinutes, staleLeaseHours, apply };
}

// A stable system node outlives app-bundled toolchains whose versioned paths move on update.
export const pickNode = (explicit, candidates = ['/opt/homebrew/bin/node', '/usr/local/bin/node'], fallback = process.execPath) =>
  explicit ? resolve(explicit) : candidates.find(path => existsSync(path)) ?? fallback;

const which = name => { try { return dirname(execFileSync('/usr/bin/which', [name], { encoding: 'utf8' }).trim()); } catch { return null; } };

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const options = parseAgentArgs(process.argv.slice(2));
    if (process.platform !== 'darwin' && options.command !== 'print') throw new Error('The launch agent is macOS-only; run project:sweep from cron or a timer elsewhere');
    // Always the primary checkout (first worktree), never the linked worktree this runs from.
    const from = resolve(options.repo ?? process.cwd());
    const root = execFileSync('git', ['worktree', 'list', '--porcelain'], { cwd: from, encoding: 'utf8' }).split('\n')[0].replace(/^worktree /, '');
    const stateDir = join(homedir(), 'Library', 'Application Support', 'river-oaks', 'project-sweep');
    const runner = join(stateDir, 'run.sh'), plist = join(homedir(), 'Library', 'LaunchAgents', `${LABEL}.plist`);
    const node = pickNode(options.node);
    if (!existsSync(node)) throw new Error(`No node at ${node}`);
    const path = [...new Set([dirname(node), '/opt/homebrew/bin', '/usr/local/bin', which('gh'), which('git'), '/usr/bin', '/bin', '/usr/sbin'].filter(Boolean))].join(':');
    const spec = { root, stateDir, node, path, apply: options.apply, fallbackRef: options.fallbackRef, staleLeaseHours: options.staleLeaseHours, intervalMinutes: options.intervalMinutes, runner };
    const domain = `gui/${process.getuid()}`;
    const loaded = () => { try { execFileSync('launchctl', ['print', `${domain}/${LABEL}`], { stdio: 'ignore' }); return true; } catch { return false; } };
    if (options.command === 'print') process.stdout.write(`# ${runner}\n${renderRunner(spec)}\n# ${plist}\n${renderPlist(spec)}`);
    else if (options.command === 'install') {
      mkdirSync(stateDir, { recursive: true, mode: 0o700 }); mkdirSync(dirname(plist), { recursive: true });
      writeFileSync(runner, renderRunner(spec)); chmodSync(runner, 0o700);
      writeFileSync(plist, renderPlist(spec));
      if (loaded()) execFileSync('launchctl', ['bootout', `${domain}/${LABEL}`], { stdio: 'ignore' });
      execFileSync('launchctl', ['bootstrap', domain, plist]);
      process.stdout.write(`Installed ${LABEL}: every ${options.intervalMinutes} min, ${options.apply ? 'APPLY (guarded retirement)' : 'report-only'}.\nRun now: launchctl kickstart ${domain}/${LABEL}\nLog: ${join(stateDir, 'sweep.log')}\nReceipts: ${join(root, '.runtime', 'project-sweep')}\n`);
    } else if (options.command === 'uninstall') {
      if (loaded()) execFileSync('launchctl', ['bootout', `${domain}/${LABEL}`]);
      if (existsSync(plist)) unlinkSync(plist);
      process.stdout.write(`Removed ${LABEL}. Receipts and ${join(stateDir, 'sweep.log')} are kept.\n`);
    } else {
      const installed = existsSync(plist), mode = existsSync(runner) ? (readFileSync(runner, 'utf8').includes(' --apply') ? 'apply' : 'report-only') : null;
      process.stdout.write(JSON.stringify({ label: LABEL, installed, loaded: loaded(), mode, plist, runner, log: join(stateDir, 'sweep.log'), receipts: join(root, '.runtime', 'project-sweep', 'latest.md') }, null, 2) + '\n');
    }
  } catch (error) { process.stderr.write(`project-sweep-agent: ${error.message}\n`); process.exitCode = 2; }
}
