"""Write a complete local clip bundle only after every staging audit passes."""

import hashlib
import json

FAMILY = "quaternius-ual-v1"
SOURCE_SHA256 = {
    "UAL1.glb": "d1cb4537efa4c06a953ca951e5935062f88c2580ac68e45045592d587bddb43d",
    "UAL2.glb": "ad3ae049c7d3d4846133b59dba6218fdabebe05d3aec646caef6665f6c540684",
}
ARCHIVES = {
    "UAL1.glb": {
        "file": "Universal Animation Library[Source].zip",
        "sha256": "28f7528643b945fc8e95362da16ee2218e82b1f4735460e707918047ed868ed5",
    },
    "UAL2.glb": {
        "file": "Universal Animation Library 2[Source].zip",
        "sha256": "85df4e989b894f2a5bb57e57637028706d674a5b92e818bbcc3b7065cb1b50e8",
    },
}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def publish_bundle(root, report, groups, joints):
    rows = {row["group"]: row for row in report["groups"]}
    if not report["ok"] or len(rows) != len(report["groups"]) or set(rows) != set(groups):
        raise ValueError("all clip groups must pass staging before publication")
    stage = root / ".runtime/quaternius-clips/staging"
    source = root / "data/raw/characters/quaternius"
    output = "preview/public/assets/animations"
    payloads, catalog = {}, {}
    for group, clips in groups.items():
        row = rows[group]
        data = (stage / f"{group}.glb").read_bytes()
        if (
            row["problems"]
            or sorted(row["clips"]) != sorted(clips)
            or len(data) != row["bytes"]
            or digest(data) != row["sha256"]
        ):
            raise ValueError(f"{group}: failed audit or staging bytes changed")
        payloads[f"{output}/{group}.glb"] = data
        catalog[group] = {
            "url": f"/assets/animations/{group}.glb",
            "family": FAMILY,
            "bytes": len(data),
            "sha256": digest(data),
            "clips": row["clips"],
            "joints": joints,
            "receipt": "/assets/animations/quaternius.sources.json",
        }
    sources, licenses = {}, {}
    for pack in ["UAL1.glb", "UAL2.glb"]:
        data = (source / pack).read_bytes()
        if digest(data) != SOURCE_SHA256[pack]:
            raise ValueError(f"{pack}: source differs from pinned archive input")
        if digest(data) != report["sources"][pack]:
            raise ValueError(f"{pack}: source changed since staging")
        sources[pack] = {"sha256": digest(data), "bytes": len(data), "archive": ARCHIVES[pack]}
        name = f"License-{pack.removesuffix('.glb')}.txt"
        license_data = (source / name).read_bytes()
        payloads[f"{output}/{name}"] = license_data
        licenses[name] = {"sha256": digest(license_data), "bytes": len(license_data)}
    receipt = {
        "schemaVersion": 1,
        "author": "Quaternius",
        "license": "CC0-1.0",
        "licenseUrl": "https://creativecommons.org/publicdomain/zero/1.0/",
        "family": FAMILY,
        "generator": report["generator"],
        "fps": report["fps"],
        "boneHeuristic": report["boneHeuristic"],
        "sources": sources,
        "licenses": licenses,
        "pipeline": {
            name: digest((root / "scripts" / name).read_bytes())
            for name in [
                "build_quaternius_clips.py",
                "quaternius_clip_audit.py",
                "quaternius_clip_publish.py",
            ]
        },
        "processing": [
            "Select the 39 approved in-place actions from UAL1 and UAL2.",
            "Export skeleton and animation only at 30 fps; preserve source joint axes.",
            "Remove root translation curves and exporter-added rest-valued root channels.",
            "Audit exact clip sets, rest transforms, hierarchy, samples and track validity.",
        ],
        "groups": rows,
    }
    payloads[f"{output}/quaternius.sources.json"] = (json.dumps(receipt, indent=2) + "\n").encode()
    payloads["preview/src/animation-clip-assets.js"] = (
        "// Generated by scripts/build_quaternius_clips.py --write after all audits pass.\n"
        "const freeze = value => {\n"
        "  for (const child of Object.values(value)) {\n"
        '    if (child && typeof child === "object") freeze(child);\n'
        "  }\n"
        "  return Object.freeze(value);\n"
        "};\n"
        "export const ANIMATION_CLIP_GROUPS = freeze(" + json.dumps(catalog, indent=2) + ");\n"
    ).encode()
    # All input checks and serialization finish before the first output mutation.
    for name, data in payloads.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(path.name + ".tmp")
        temporary.write_bytes(data)
        temporary.replace(path)
    return list(payloads)
