import * as THREE from 'three';
import {createHash} from 'node:crypto';
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {loadCharacterRig} from '../preview/tests/helpers/character-rig.js';
import {loadResidentAvatar} from '../preview/src/avatars.js';
import {createDressSkirtGeometry} from '../preview/src/skirt-geometry.js';
import {skinSkirt} from '../preview/src/skirt-skinning.js';
import {createVesperTrimGeometry} from '../preview/src/vesper-skirt-geometry.js';
import {bakeSkirtDetail} from './lib/skirt-detail-fit.mjs';
import {prepareSeatedSkirtFit} from './lib/skirt-seat-fit.mjs';

// Rebuild from the authored recipe and original rig, never from the installed
// corrective. Textures are omitted by the existing real-rig test loader.
const write = process.argv.includes('--write');
if (process.argv.slice(2).some(arg => !['--write', '--check'].includes(arg))) throw new Error('Use --check (default) or --write');
const root = new URL('../', import.meta.url);
const source = await loadCharacterRig('jevica'), previousLoad = GLTFLoader.prototype.loadAsync;
const previousWindow = globalThis.window, previousDocument = globalThis.document;
GLTFLoader.prototype.loadAsync = async () => ({scene: source.scene});
globalThis.window = {matchMedia: () => ({matches: false})};
globalThis.document = {createElement: () => ({getContext: () => new Proxy({}, {get: () => () => {}})})};
let avatar, geometry, material, group, trimGeometry, trimGroup;
try {
  avatar = await loadResidentAvatar(4, 'remote-skirt-bake', 'jevica', {folk: false, appearanceId: 'jevica', faceRecipe: {}});
  const model = avatar.rig.model, pelvis = model.getObjectByName('pelvis');
  model.updateWorldMatrix(true, true);
  const attachment = new THREE.Group();
  attachment.quaternion.copy(pelvis.getWorldQuaternion(new THREE.Quaternion()).invert().multiply(model.getWorldQuaternion(new THREE.Quaternion())));
  pelvis.add(attachment);
  geometry = createDressSkirtGeometry({slit: false}); material = new THREE.MeshBasicMaterial({side: THREE.DoubleSide});
  const raw = new THREE.Mesh(geometry, material); attachment.add(raw);
  const fitted = skinSkirt(raw, model.getObjectByName('Jevica')); group = fitted.group;
  const skirt = fitted.mesh;
  trimGeometry = createVesperTrimGeometry();
  const rawTrim = new THREE.Mesh(trimGeometry, material); attachment.add(rawTrim);
  const trim = skinSkirt(rawTrim, model.getObjectByName('Jevica')); trimGroup = trim.group;
  avatar.object.updateMatrixWorld(true);
  const sourcePositions = Array.from(geometry.attributes.position.array), sourceWeights = Array.from(geometry.attributes.skinWeight.array);
  const fit = prepareSeatedSkirtFit(skirt, model);
  const rest = geometry.attributes.position.array.slice(), normals = geometry.attributes.normal.array.slice();
  avatar.object.position.y = .55 - avatar.rig.hipHeight + .025;
  for (let frame = 0; frame <= 144; frame++) avatar.update(frame * 1000 / 60, 'continue', false, {speed: 0, distance: 0, riding: true, ridingKind: 'seat', seatToFloor: .55}, () => 0);
  avatar.object.updateMatrixWorld(true);
  const diagnostic = fit();
  if (diagnostic.activation !== 1 || diagnostic.tested < 200 || diagnostic.penetrating !== 0) throw new Error(`Seated fit failed: ${JSON.stringify(diagnostic)}`);
  const data = {version: 1, sourcePositions, sourceWeights,
    positionDelta: Array.from(geometry.attributes.position.array, (value, i) => Math.fround(value - rest[i])),
    normalDelta: Array.from(geometry.attributes.normal.array, (value, i) => Math.fround(value - normals[i])),
  };
  const detail = bakeSkirtDetail(skirt, rest, trim.mesh);
  const header = '// Generated by node scripts/bake-vesper-skirt.mjs --write.\n// Pinned authored Vesper skirt and wrap trim on the shipped Jevica rig; see the adjacent receipt.\n';
  const output = `${header}export const VESPER_SKIRT_MORPH = ${JSON.stringify(data)};\nexport const VESPER_TRIM_MORPH = ${JSON.stringify(detail.data)};\n`;
  const inputs = {};
  for (const name of ['pnpm-lock.yaml', 'preview/public/assets/characters/jevica.glb', 'preview/public/assets/characters/jevica.sources.json', 'preview/src/avatars.js', 'preview/src/foot-placement.js', 'preview/src/foot-roll.js', 'preview/src/sole-support.js', 'preview/src/skirt-geometry.js', 'preview/src/skirt-skinning.js', 'preview/src/vesper-skirt-geometry.js', 'scripts/lib/skirt-detail-fit.mjs', 'preview/tests/helpers/character-rig.js', 'scripts/lib/skirt-seat-fit.mjs', 'scripts/bake-vesper-skirt.mjs']) inputs[name] = createHash('sha256').update(await readFile(new URL(name, root))).digest('hex');
  const receipt = JSON.stringify({version: 1, provenance: 'Repository-authored corrective fitted to the shipped rig; base asset source and license are recorded in preview/public/assets/characters/jevica.sources.json.', scope: 'Offline symmetric seated fit; front garment samples against upper thighs only. Runtime/other-pose and rendered acceptance are separate.', command: 'node scripts/bake-vesper-skirt.mjs --check', inputs, outputSha256: createHash('sha256').update(output).digest('hex'), vertices: rest.length / 3, triangles: geometry.index.count / 3, trimVertices: trimGeometry.attributes.position.count, maximumTrimOffset: detail.maximumDistance, diagnostic}, null, 2) + '\n';
  for (const [path, expected] of [['preview/src/vesper-skirt-morph-data.js', output], ['preview/src/vesper-skirt-morph-receipt.json', receipt]]) {
    const target = new URL(path, root);
    if (write) await writeFile(target, expected);
    else if (await readFile(target, 'utf8') !== expected) throw new Error(`Bake differs: ${fileURLToPath(target)}. Review inputs and run --write intentionally.`);
  }
  console.log(`${write ? 'Wrote' : 'Verified'} seated skirt bake: ${rest.length / 3} vertices, ${geometry.index.count / 3} triangles; ${diagnostic.tested} contact samples, no penetrations.`);
} finally {
  trimGroup?.removeFromParent(); trimGeometry?.dispose(); group?.removeFromParent(); geometry?.dispose(); material?.dispose(); avatar?.dispose();
  GLTFLoader.prototype.loadAsync = previousLoad; globalThis.window = previousWindow; globalThis.document = previousDocument;
}
