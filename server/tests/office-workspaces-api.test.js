import test from 'node:test';
import assert from 'node:assert/strict';
import * as api from '../office-workspaces-api.js';
import { createMemoryOfficeWorkspaces } from '../office-workspaces.js';
const task={id:'one',title:'Shared task',notes:'',result:'',links:[],status:'open'};
test('workspace API requires same-session visit for tasks and explicit accepted membership',async()=>{
 assert.equal(typeof api.officeWorkspaceAction,'function');
 const workspaces=createMemoryOfficeWorkspaces();let active=null,approved=true;
 const call=(user,action,data={})=>api.officeWorkspaceAction({action,identity:{userId:user,sessionId:user},workspaces,readBody:async()=>data,visit:async()=>active,allow:async()=>true,isApproved:async()=>approved});
 const a=(await call('alice','provision')).value.workspace;
 assert.equal((await call('bob','read',{workspaceId:a.id})).status,403);
 assert.equal((await call('alice','read',{workspaceId:a.id})).status,403,'owner needs active visit');
 assert.equal((await call('alice','invite',{workspaceId:a.id,peerId:'bob'})).status,200);
 active={id:a.id};
 assert.equal((await call('bob','read',{workspaceId:a.id})).status,403,'invitation is not acceptance');
 assert.equal((await call('bob','accept',{workspaceId:a.id})).status,200);
 assert.equal((await call('bob','save',{workspaceId:a.id,expectedVersion:0,operationId:'one',task})).status,200);
 assert.equal((await call('bob','read',{workspaceId:a.id,userId:'alice'})).status,400);
 active={id:'jevica-office'};assert.equal((await call('bob','read',{workspaceId:a.id})).status,403,'another office is not authorization');
 assert.equal((await call('bob','revoke',{workspaceId:a.id,peerId:'alice'})).status,403);
 approved=false;assert.equal((await call('alice','invite',{workspaceId:a.id,peerId:'stranger'})).status,403,'unapproved peers cannot be invited');
 approved=true;assert.equal((await call('alice','revoke',{workspaceId:a.id,peerId:'bob'})).status,200);
 active={id:a.id};assert.equal((await call('bob','read',{workspaceId:a.id})).status,403);
});
test('workspace API fails closed on limits, invalid fields, and unavailable storage',async()=>{
 assert.equal(typeof api.officeWorkspaceAction,'function');
 const base={action:'provision',identity:{userId:'alice'},workspaces:createMemoryOfficeWorkspaces(),readBody:async()=>({}),visit:async()=>null,allow:async()=>true,isApproved:async()=>true};
 assert.equal((await api.officeWorkspaceAction({...base,allow:async()=>false})).status,429);
 assert.equal((await api.officeWorkspaceAction({...base,workspaces:null})).status,503);
 assert.equal((await api.officeWorkspaceAction({...base,readBody:async()=>({ownerId:'bob'})})).status,400);
 assert.equal((await api.officeWorkspaceAction({...base,workspaces:{provision:async()=>{throw Error('storage unavailable');}}})).status,503);
});
